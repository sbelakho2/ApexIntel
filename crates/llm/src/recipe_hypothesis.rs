#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recipe_candidate_confidence_clamp() {
        let mut candidate = RecipeCandidate {
            code: "TEST".into(),
            name: "Test".into(),
            description: "desc".into(),
            category: "supply_chain".into(),
            severity: "warning".into(),
            regions: vec!["TN".into()],
            signals: vec![],
            confidence_threshold: 1.5, // invalid
            narrative_template: "".into(),
            action_template: "".into(),
            hypothesis_rationale: "".into(),
            estimated_base_rate: -0.1, // invalid
            expected_precision: 2.0,   // invalid
        };
        candidate.confidence_threshold = candidate.confidence_threshold.clamp(0.5, 0.99);
        candidate.estimated_base_rate = candidate.estimated_base_rate.clamp(0.0, 1.0);
        candidate.expected_precision = candidate.expected_precision.clamp(0.0, 1.0);
        assert_eq!(candidate.confidence_threshold, 0.99);
        assert_eq!(candidate.estimated_base_rate, 0.0);
        assert_eq!(candidate.expected_precision, 1.0);
    }
}
